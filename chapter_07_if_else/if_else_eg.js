let percentage = 75;

if (percentage >= 90) {
    console.log("Topper");
}

else if (percentage >= 80) {
    console.log("Distinction");
}

else if (percentage >= 70) {
    console.log("First class");
}

else if (percentage >= 60) {
    console.log("Just pass");
}

else {
    console.log("failed");
}