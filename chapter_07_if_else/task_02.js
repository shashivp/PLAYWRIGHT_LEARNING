//students grade
// 90 and above → A

// - 80–89 → B

// - 70–79 → C

// - 60–69 → D

// - Below 60 → Fail


let score = 75;

if (score >= 90) {
    console.log("Grade A");
}

else if (score >= 80 ) {
    console.log("Grade B");
}

else if (score >= 70 ) {
    console.log("Grade c");
}

else if (score >= 60 ) {
    console.log("Grade D");
}

else {
    console.log("student failed");
}