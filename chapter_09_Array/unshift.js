//push, pop, unshift, shift:


//push "arr.push()" : add value at the last index
//pop "arr.pop()" : remove value from last index
//unshift: add at the begining
//shift; remove from the begining


let abc = ["shashi", "vp", "ko"];

//unshift: will add element at 0th index
abc.unshift(100);
console.log(abc);

abc.unshift("added from begining");
console.log(abc);

abc.unshift(200.75);
console.log(abc);

abc.unshift(1);
console.log(abc);
